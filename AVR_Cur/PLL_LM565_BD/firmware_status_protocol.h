#ifndef FIRMWARE_STATUS_PROTOCOL_H
#define FIRMWARE_STATUS_PROTOCOL_H

#define ATMEGA8_BOOT_NOTICE    0xA8
#define ATMEGA8_STATUS_REQUEST 0xA9
#define ATMEGA8_BOOT_ACK       0xAA
#define ATMEGA8_STATUS_REPLY   0xAB
#define ATMEGA8_UPLOAD_NOTICE  0xAC
#define ATMEGA8_UPLOAD_ACK     0xAD

/* 두 MCU를 함께 갱신해야 제어 오류를 운전 오류로 처리할 수 있다. */
#define ATMEGA8_CONTROL_FAULT  0x1A

#define ATMEGA8_UPLOAD_MARKER_ADDRESS 0x01F8
#define ATMEGA8_UPLOAD_MARKER_LENGTH 8
#define ATMEGA8_UPLOAD_MARKER_BYTES 0x35, 0xC6, 0xA2, 0x79, 0xD4, 0x18, 0xEB, 0x5C

#endif
